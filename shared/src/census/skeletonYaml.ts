// The frozen Day-1 skeleton's file format (content/census/day1.yaml): block style down to each member, leaf records
// (job, portrait, look, links) on one line each. Shared by tools/census.ts (which builds it) and tools/gen-residents.ts
// (which records M-03 step 2's progress in it), so a rewrite keeps the file byte for byte where nothing changed. Pure.
import YAML from "yaml";
import type { Day1Skeleton } from "./skeleton";

const FLOW = new Set(["library", "job", "portrait", "generation", "age_range", "first_names"]);

export const SKELETON_HEADER = [
  "# The Day-1 census skeleton (MVP M-03 step 1; GDD Appendix A.1): 123 households, 210 homed residents, before any new",
  "# card is written. GENERATED by `npm run census:skeleton` from content/census/pins.yaml, content/places/homes.yaml,",
  "# the portrait library and the persona cards (shared/src/census/skeleton.ts). Frozen: rebuild only with --reseed.",
  "# `npm run census:report` recomputes every A.1 table from this file. Portraits: { source: card } keeps the card's,",
  "# { source: library, id } is a library identity, { source: procedural, look, tags } a seeded look (D1).",
].join("\n");

export function stringifySkeleton(sk: Day1Skeleton): string {
  const doc = new YAML.Document(sk);
  YAML.visit(doc, {
    Pair(_, pair) {
      const key = YAML.isScalar(pair.key) ? String(pair.key.value) : "";
      if (FLOW.has(key) && (YAML.isMap(pair.value) || YAML.isSeq(pair.value))) pair.value.flow = true;
      if (key === "links" && YAML.isSeq(pair.value)) for (const item of pair.value.items) if (YAML.isMap(item)) item.flow = true;
    },
  });
  return `${SKELETON_HEADER}\n${doc.toString({ lineWidth: 0, flowCollectionPadding: true })}`;
}
