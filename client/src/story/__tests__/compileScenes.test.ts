import { execFileSync } from 'node:child_process';
import { readFileSync, statSync } from 'node:fs';
import { resolve } from 'node:path';
import { expect, it } from 'vitest';
it('compiling unchanged scenes preserves generated bytes and modification time', () => {
  const root = resolve(import.meta.dirname, '../../../..');
  const compile = () => execFileSync(process.execPath, ['--import', 'tsx', 'tools/compile-scenes.ts', '--quiet'], { cwd: root, stdio: 'pipe' });
  compile();
  const file = resolve(root, 'client/src/story/scenes.gen.json');
  const before = readFileSync(file, 'utf8'), modified = statSync(file).mtimeMs;
  compile();
  expect(readFileSync(file, 'utf8')).toBe(before); expect(statSync(file).mtimeMs).toBe(modified);
}, 30_000);
