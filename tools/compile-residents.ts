/**
 * The client's resident roster (MVP M-03 step 3): every persona card, checked against the shared schema, compiled into
 * client/src/world/residents.gen.json (gitignored; built before `vite`, `vite build` and the tests, like scenes.gen.json).
 *
 * Order is the roster's: the hand-written cards (content/residents/*.yaml) in file order, as the client has always
 * loaded them, then the Day-1 census's cards (content/residents/day1/*.yaml) by id. Roster colours and indices key off
 * that order, so the core cast never moves when the census is written. With no Day-1 cards it is the same 24.
 *
 * Run: npm run residents      (exit 1 on a bad card or a duplicate id)
 */
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { PersonaCard } from "@monde/shared";

const root = path.resolve(import.meta.dirname, "..");
const handDir = path.join(root, "content/residents");
const day1Dir = path.join(handDir, "day1");
const outFile = path.join(root, "client/src/world/residents.gen.json");

const errors: string[] = [];
function load(dir: string): PersonaCard[] {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter(f => f.endsWith(".yaml")).sort().flatMap(f => {
    const where = path.relative(root, path.join(dir, f));
    const parsed = PersonaCard.safeParse(YAML.parse(fs.readFileSync(path.join(dir, f), "utf8")));
    if (!parsed.success) { errors.push(`${where}: ${parsed.error.issues.slice(0, 3).map(i => `${i.path.join(".")}: ${i.message}`).join("; ")}`); return []; }
    return [parsed.data];
  });
}

const hand = load(handDir);
const day1 = load(day1Dir).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
const seen = new Set<string>();
for (const c of [...hand, ...day1]) {
  if (seen.has(c.id)) errors.push(`duplicate resident id ${c.id}`);
  seen.add(c.id);
}
if (errors.length) {
  for (const e of errors) console.error(e);
  process.exit(1);
}

// Generated by tools/compile-residents.ts from content/residents. Do not edit; edit the cards. One card per line.
const output = `{"version":1,"hand":${hand.length},"cards":[\n${[...hand, ...day1].map(c => JSON.stringify(c)).join(",\n")}\n]}\n`;
if (!fs.existsSync(outFile) || fs.readFileSync(outFile, "utf8") !== output) fs.writeFileSync(outFile, output);
console.log(`residents: ${hand.length} hand-written + ${day1.length} Day-1 cards → ${path.relative(root, outFile)} (${(output.length / 1024).toFixed(0)} KB)`);
