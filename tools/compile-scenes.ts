/**
 * Scene compiler CLI (GDD §13.1, §20.4). Compiles every content/scenes/*.scene.md against content/flags.yaml,
 * the persona cards and the place registry, prints a report, writes client/src/story/scenes.gen.json and exits
 * 1 if any scene has errors.
 *
 * Run: npm run scenes            (add --quiet to hide warnings)
 */
import fs from "node:fs";
import path from "node:path";
import {
  compileScenes, formatDiagnostic, registryFromContent, type CompiledScene, type Diagnostic,
} from "../shared/src/script/index";

const root = path.resolve(import.meta.dirname, "..");
const quiet = process.argv.includes("--quiet");
const read = (p: string) => fs.readFileSync(path.join(root, p), "utf8");

const residentsDir = path.join(root, "content/residents");
const reg = registryFromContent({
  flagsYaml: read("content/flags.yaml"),
  residentYamls: fs.readdirSync(residentsDir).filter((f) => f.endsWith(".yaml")).sort().map((f) => read(`content/residents/${f}`)),
  placesYaml: read("content/places/places.yaml"),
});

const scenesDir = "content/scenes";
const files = fs.readdirSync(path.join(root, scenesDir)).filter((f) => f.endsWith(".scene.md")).sort(sceneOrder);
const { scenes, byFile } = compileScenes(files.map((f) => ({ file: `${scenesDir}/${f}`, source: read(`${scenesDir}/${f}`) })), reg);

// ---- report
const byId = new Map(scenes.map((s) => [s.file, s]));
const rows: string[][] = [["scene", "lines", "choices", "errors", "warnings"]];
let errors = 0, warnings = 0, totalLines = 0, totalChoices = 0;
for (const f of files) {
  const file = `${scenesDir}/${f}`;
  const d = byFile.get(file) ?? [];
  const s = byId.get(file);
  const e = d.filter((x) => x.severity === "error").length;
  const w = d.length - e;
  errors += e; warnings += w;
  totalLines += s?.stats.lines ?? 0; totalChoices += s?.stats.choices ?? 0;
  rows.push([s?.id ?? f, String(s?.stats.lines ?? "-"), String(s?.stats.choices ?? "-"), e ? String(e) : "·", w ? String(w) : "·"]);
}
const widths = rows[0]!.map((_, c) => Math.max(...rows.map((r) => r[c]!.length)));
for (const r of rows) console.log(r.map((cell, c) => (c === 0 ? cell.padEnd(widths[c]!) : cell.padStart(widths[c]!))).join("  "));
console.log("");

const all: Diagnostic[] = files.flatMap((f) => byFile.get(`${scenesDir}/${f}`) ?? []);
for (const d of all) if (d.severity === "error" || !quiet) (d.severity === "error" ? console.error : console.warn)(formatDiagnostic(d));
if (all.length) console.log("");

// ---- output
const outFile = path.join(root, "client/src/story/scenes.gen.json");
fs.mkdirSync(path.dirname(outFile), { recursive: true });
const out = {
  // Generated by tools/compile-scenes.ts from content/scenes. Do not edit; edit the .scene.md files.
  version: 1,
  diagnostics: { errors, warnings },
  scenes: Object.fromEntries(scenes.map((s): [string, CompiledScene] => [s.id, s])),
};
const output = stringify(out) + "\n";
if (!fs.existsSync(outFile) || fs.readFileSync(outFile, "utf8") !== output) fs.writeFileSync(outFile, output);

console.log(
  `scenes: ${scenes.length} compiled from ${files.length} files · ${totalLines} lines, ${totalChoices} choices · ` +
    `${errors} errors, ${warnings} warnings → ${path.relative(root, outFile)}`,
);
process.exit(errors ? 1 : 0);

/** s01a < s01b < … < s23 < e1 … < epilogue_e1 … < inserts. */
function sceneOrder(a: string, b: string): number {
  const rank = (f: string) => (f.startsWith("s") ? 0 : f.startsWith("e") && !f.startsWith("epilogue") ? 1 : f.startsWith("epilogue") ? 2 : 3);
  return rank(a) - rank(b) || a.localeCompare(b);
}

/** JSON with one op / option per line: readable diffs without a line per field. */
function stringify(v: unknown, indent = "", depth = 0): string {
  const inline = depth >= 4 || v === null || typeof v !== "object";
  if (inline) return JSON.stringify(v);
  const next = indent + " ";
  if (Array.isArray(v)) {
    if (v.length === 0) return "[]";
    return `[\n${v.map((x) => next + stringify(x, next, depth + 1)).join(",\n")}\n${indent}]`;
  }
  const entries = Object.entries(v as Record<string, unknown>).filter(([, x]) => x !== undefined);
  if (entries.length === 0) return "{}";
  return `{\n${entries.map(([k, x]) => `${next}${JSON.stringify(k)}: ${stringify(x, next, depth + 1)}`).join(",\n")}\n${indent}}`;
}
